function readRecordSearchParam(params: Record<string, string | string[] | undefined>, key: string): string {
  const value = params[key];
  if (Array.isArray(value)) {
    return value[0] ?? "";
  }
  return value ?? "";
}

export function readSearchParam(params: SearchParamsLike, key: string): string {
  if (params instanceof URLSearchParams) {
    return params.get(key) ?? "";
  }
  return readRecordSearchParam(params, key);
}

export function normalizeUiLanguage(value: unknown, fallback: UiLanguage = "fr"): UiLanguage {
  const normalized = String(value ?? "").trim().toLowerCase();
  if (normalized === "en") {
    return "en";
  }
  if (normalized === "fr") {
    return "fr";
  }
  return fallback;
}

export function uiLanguageFromSearchParams(params: SearchParamsLike, fallback: UiLanguage = "fr"): UiLanguage {
  return normalizeUiLanguage(readSearchParam(params, "lang"), fallback);
}

export function uiLanguageFromAcceptLanguage(headerValue: string | null | undefined, fallback: UiLanguage = "fr"): UiLanguage {
  const raw = String(headerValue ?? "").trim().toLowerCase();
  return raw.startsWith("en") ? "en" : fallback;
}

export function setQueryParams(
  path: string,
  updates: Record<string, string | number | null | undefined>,
): string {
  const [pathname, rawSearch = ""] = path.split("?");
  const params = new URLSearchParams(rawSearch);
  for (const [key, value] of Object.entries(updates)) {
    if (value === null || value === undefined || value === "") {
      params.delete(key);
    } else {
      params.set(key, String(value));
    }
  }
  const nextSearch = params.toString();
  return nextSearch ? `${pathname}?${nextSearch}` : pathname;
}

export function withUiLanguage(path: string, language: UiLanguage | null | undefined): string {
  if (!language) {
    return path;
  }
  return setQueryParams(path, { lang: language });
}

function withOptionalStatusSuffix(baseMessage: string, statusCode: string): string {
  return statusCode ? `${baseMessage} (${statusCode})` : baseMessage;
}

export function translateUiMessage(language: UiLanguage, code: string, args: UiMessageArgs = {}): string {
  const normalizedCode = String(code || "").trim();
  const statusCode = String(args.statusCode ?? "").trim();
  const detail = String(args.detail ?? "").trim();
  const baseMessage = UI_MESSAGES[language][normalizedCode];

  if (!baseMessage) {
    return detail || normalizedCode;
  }

  const resolvedMessage = baseMessage.includes("{detail}")
    ? baseMessage.replaceAll("{detail}", detail)
    : baseMessage;

  if (
    normalizedCode === "contract_unavailable"
    || normalizedCode === "export_unavailable"
    || normalizedCode === "invoice_unavailable"
    || normalizedCode === "quote_pdf_unavailable"
  ) {
    return withOptionalStatusSuffix(resolvedMessage, statusCode);
  }

  return resolvedMessage;
}

export function resolveUiFlashMessage(
  params: SearchParamsLike,
  language: UiLanguage,
  kind: FlashKind,
): string {
  const directMessage = readSearchParam(params, kind).trim();
  if (directMessage) {
    return translateBackendMessage(language, directMessage);
  }

  const code = readSearchParam(params, `${kind}_code`).trim();
  if (!code) {
    return "";
  }

  return translateUiMessage(language, code, {
    detail: readSearchParam(params, "detail"),
    statusCode: readSearchParam(params, "status_code"),
  });
}

export function withUiMessageCode(
  path: string,
  kind: FlashKind,
  code: string,
  args: UiMessageArgs = {},
): string {
  const otherKind: FlashKind = kind === "ok" ? "error" : "ok";
  const updates: Record<string, string | number | null | undefined> = {
    [kind]: null,
    [`${kind}_code`]: code,
    [otherKind]: null,
    [`${otherKind}_code`]: null,
    detail: args.detail ?? null,
    status_code: args.statusCode ?? null,
  };
  if (args.lang) {
    updates.lang = args.lang;
  }
  return setQueryParams(path, updates);
}
