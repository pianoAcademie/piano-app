export function normalizeUiLanguage(value: string | null | undefined): UiLanguage {
  return String(value || "").trim().toLowerCase() === "en" ? "en" : "fr";
}

export function localeForUiLanguage(language: UiLanguage): string {
  return language === "en" ? "en-GB" : "fr-FR";
}

export function uiText(language: UiLanguage, key: string, values?: TranslationValues): string {
  const fallback = UI_TEXT.fr[key] || key;
  const template = UI_TEXT[language][key] || fallback;
  if (!values) {
    return template;
  }
  return template.replace(/\{(\w+)\}/g, (_match, token) => String(values[token] ?? ""));
}
